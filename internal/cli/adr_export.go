package cli

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"tasks-ai/internal/core"

	"github.com/spf13/cobra"
)

// generatedNote is the mark the export leaves in every file it writes: el
// archivo no es la fuente, y editarlo a mano pierde el cambio.
const generatedNote = "<!-- Generated by tasks-ai adr export: do not edit by hand. -->"

// exportedIndex is the name of the index of the directory.
const exportedIndex = "README.md"

// newADRExportCommand writes the register to a directory of markdown files.
func newADRExportCommand() *cobra.Command {
	var (
		dir   string
		check bool
	)

	command := &cobra.Command{
		Use:   "export",
		Short: "Writes the ADRs to a directory of markdown files",
		Long: "Writes one markdown file per ADR and the index of the directory from the register.\n" +
			"This is the versioned copy that Git reviews and that the adr-software gate reads: the\n" +
			"database is the source, so the files are generated and a hand edit is lost on the\n" +
			"next export. With --check nothing is written: it says whether the directory differs\n" +
			"from the register and exits with 1 when it does.",
		Args: usage(cobra.NoArgs),
		RunE: func(command *cobra.Command, _ []string) error {
			if err := adrDir(dir); err != nil {
				return err
			}

			return withProject(command, func(opened *project) error {
				adrs, err := opened.core.AllADRs(command.Context())
				if err != nil {
					return err
				}

				files, err := renderedADRs(adrs, dir)
				if err != nil {
					return err
				}

				if check {
					return checkExport(command, dir, files)
				}

				return writeExport(command, dir, files)
			})
		},
	}

	command.Flags().StringVar(&dir, "dir", "", "directory of markdown ADR files (required)")
	command.Flags().BoolVar(&check, "check", false, "reports whether the directory differs from the register, without writing")

	return command
}

// exportReport es lo que la exportación responde: lo que escribió o, con
// --check, lo que difiere.
type exportReport struct {
	Dir     string   `json:"dir"`
	Files   []string `json:"files,omitempty"`
	Drifted []string `json:"drifted,omitempty"`
}

// writeExport writes every generated file and answers with their names.
func writeExport(command *cobra.Command, dir string, files map[string]string) error {
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return fmt.Errorf("creating the directory of ADR files %s: %w", dir, err)
	}

	names := sortedNames(files)
	for _, name := range names {
		//nolint:gosec // la ruta se compone con el directorio que la persona nombró
		if err := os.WriteFile(filepath.Join(dir, name), []byte(files[name]), 0o644); err != nil {
			return fmt.Errorf("writing %s: %w", name, err)
		}
	}

	return writeJSON(command.OutOrStdout(), exportReport{Dir: dir, Files: names})
}

// checkExport answers with the files that differ from the register, and refuses
// the operation when there is any: la deriva se corrige exportando.
func checkExport(command *cobra.Command, dir string, files map[string]string) error {
	drifted := []string{}

	for _, name := range sortedNames(files) {
		//nolint:gosec // la ruta se compone con el directorio que la persona nombró
		raw, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil || string(raw) != files[name] {
			drifted = append(drifted, name)
		}
	}

	if err := writeJSON(command.OutOrStdout(), exportReport{Dir: dir, Drifted: drifted}); err != nil {
		return err
	}

	if len(drifted) > 0 {
		return errors.New("the export differs from the register: run adr export to write it")
	}

	return nil
}

// renderedADRs composes the markdown of every ADR and of the index, by name.
func renderedADRs(adrs []core.ADR, dir string) (map[string]string, error) {
	slugs := make(map[int]string, len(adrs))
	for _, adr := range adrs {
		slugs[adr.Number] = adr.Slug
	}

	files := make(map[string]string, len(adrs)+1)
	entries := make([]string, 0, len(adrs))

	for _, adr := range adrs {
		name, err := adrFileNameOf(adr)
		if err != nil {
			return nil, err
		}

		files[name] = renderADR(adr, slugs)
		entries = append(entries, fmt.Sprintf("- [%s: %s](%s) (%s, %s)",
			adr.Ref, adr.Title, name, adr.Status, adr.Date))
	}

	files[exportedIndex] = renderIndex(dir, entries)

	return files, nil
}

// adrFileNameOf composes the name of the file an ADR is exported to.
func adrFileNameOf(adr core.ADR) (string, error) {
	if adr.Number < 1 || adr.Slug == "" {
		return "", fmt.Errorf("ADR %q cannot name a file", adr.Ref)
	}

	return fmt.Sprintf("%03d-%s.md", adr.Number, adr.Slug), nil
}

// renderADR composes the markdown of one ADR: su frontmatter, su título, sus
// secciones y, cuando está sustituido, el enlace al sustituto.
func renderADR(adr core.ADR, slugs map[int]string) string {
	var out strings.Builder

	out.WriteString("---\n")
	fmt.Fprintf(&out, "status: %s\n", statusLine(adr, slugs))
	fmt.Fprintf(&out, "date: %s\n", adr.Date)
	fmt.Fprintf(&out, "decision-makers: %q\n", adr.Deciders)
	out.WriteString("---\n\n")
	out.WriteString(generatedNote + "\n\n")
	fmt.Fprintf(&out, "# %s: %s\n", adr.Ref, adr.Title)

	writeSection(&out, "Contexto", adr.Context)
	writeSection(&out, "Decisión", adr.Decision)
	writeSection(&out, "Consecuencias", adr.Consequences)

	if adr.Alternatives != nil {
		writeSection(&out, "Alternativas consideradas", *adr.Alternatives)
	}

	if adr.MoreInfo != nil {
		writeSection(&out, "Más información", *adr.MoreInfo)
	}

	return out.String()
}

// writeSection writes one section of the body, and nothing when it is empty.
func writeSection(out *strings.Builder, heading, body string) {
	if strings.TrimSpace(body) == "" {
		return
	}

	fmt.Fprintf(out, "\n## %s\n\n%s\n", heading, strings.TrimRight(body, "\n"))
}

// statusLine composes the frontmatter state: el sustituido enlaza a su
// sustituto, con el nombre del archivo que tiene en el directorio.
func statusLine(adr core.ADR, slugs map[int]string) string {
	if adr.SupersededBy == nil {
		return adr.Status
	}

	number, err := core.ParseADRRef(*adr.SupersededBy)
	if err != nil {
		return adr.Status
	}

	slug, ok := slugs[number]
	if !ok {
		return adr.Status
	}

	return fmt.Sprintf("superseded by [%s](%s)", core.ADRRef(number), fmt.Sprintf("%03d-%s.md", number, slug))
}

// renderIndex composes the index of the directory.
func renderIndex(dir string, entries []string) string {
	var out strings.Builder

	out.WriteString("# Decisiones de arquitectura (ADR)\n\n")
	out.WriteString(generatedNote + "\n\n")
	out.WriteString("Un Architecture Decision Record (ADR) recoge una decisión de arquitectura relevante con su\n")
	out.WriteString("contexto y sus consecuencias. Este índice enlaza los registros del directorio; no repite sus\n")
	out.WriteString("decisiones.\n\n")
	out.WriteString("## Convenciones\n\n")
	fmt.Fprintf(&out, "- Directorio: `%s`\n", dir)
	out.WriteString("- Nombres: `NNN-titulo-con-guiones.md`.\n")
	out.WriteString("- Estados: `proposed`, `accepted`, `rejected`, `deprecated`, `superseded`.\n\n")
	out.WriteString("## ADR\n\n")

	for _, entry := range entries {
		out.WriteString(entry + "\n")
	}

	return out.String()
}

// sortedNames lists the files of the export by name, with the index last: el
// índice se lee después de los registros que enlaza.
func sortedNames(files map[string]string) []string {
	names := make([]string, 0, len(files))

	for name := range files {
		if name != exportedIndex {
			names = append(names, name)
		}
	}

	sort.Strings(names)

	return append(names, exportedIndex)
}
